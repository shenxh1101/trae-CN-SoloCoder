def train_idf(corpus):
    doc_count = len(corpus)
    word_doc_freq = defaultdict(int)
    
    for doc in corpus:
        words = set(jieba.lcut(doc))
        for word in words:
            if len(word) > 1:
                word_doc_freq[word] += 1
    
    idf_dict = {}
    for word, freq in word_doc_freq.items():
        idf = math.log((doc_count + 1) / (freq + 1)) + 1
        idf_dict[word] = round(idf, 4)
    
    return idf_dict

if __name__ == "__main__":
    idf_dict = train_idf(corpus)
    
    with open("data/idf_dict.json", "w", encoding="utf-8") as f:
        json.dump(idf_dict, f, ensure_ascii=False, indent=2)
    
    print(f"IDF字典已保存，共包含 {len(idf_dict)} 个词汇")
    print("示例词汇IDF值:")
    for word in list(idf_dict.keys())[:10]:
        print(f"  {word}: {idf_dict[word]}")
