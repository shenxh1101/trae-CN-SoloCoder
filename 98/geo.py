def _ip_to_int(ip_str: str) -> Optional[int]:
    try:
        parts = ip_str.split('.')
        if len(parts) != 4:
            return None
        return sum(int(p) << (8 * (3 - i)) for i, p in enumerate(parts))
    except (ValueError, TypeError):
        return None


def _lookup_online(ip: str) -> Optional[str]:
    try:
        url = f'http://ip-api.com/json/{ip}?fields=status,countryCode'
        req = urllib.request.Request(url, headers={'User-Agent': 'logalyzer/1.0'})
        with urllib.request.urlopen(req, timeout=2) as r:
            data = json.loads(r.read().decode('utf-8'))
            if data.get('status') == 'success':
                return data.get('countryCode')
    except Exception:
        pass
    return None


def _lookup_local(ip_int: int) -> Optional[str]:
    if 167772160 <= ip_int <= 184549375:
        return 'Local'
    if 2130706432 <= ip_int <= 2147483647:
        return 'Local'
    if 2886729728 <= ip_int <= 2887778303:
        return 'Local'
    if 3232235520 <= ip_int <= 3232301055:
        return 'Local'

    for country, ranges in IP_RANGES.items():
        for start_str, end_str in ranges:
            start = _ip_to_int(start_str)
            end = _ip_to_int(end_str)
            if start is not None and end is not None and start <= ip_int <= end:
                return country
    return None


_cache = {}
_use_online = False


@lru_cache(maxsize=10000)
def ip_to_country(ip: str) -> str:
    if ip in _cache:
        return _cache[ip]

    ip_int = _ip_to_int(ip)
    if ip_int is None:
        _cache[ip] = 'Unknown'
        return 'Unknown'

    result = _lookup_local(ip_int)
    if result:
        _cache[ip] = result
        return result

    if _use_online:
        result = _lookup_online(ip)
        if result:
            _cache[ip] = result
            return result

    _cache[ip] = 'Unknown'
    return 'Unknown'


def disable_online_lookup():
    global _use_online
    _use_online = False


def enable_online_lookup():
    global _use_online
    _use_online = True


def country_name(code: str) -> str:
    return COUNTRY_NAMES.get(code, code)


def generate_world_map(country_counts: List[Tuple[str, int]],
                       title: str = 'GEOGRAPHIC DISTRIBUTION') -> str:
    if not country_counts:
        return 'No geographic data available.'

    count_dict = dict(country_counts)
    total = sum(count_dict.values())
    if total == 0:
        total = 1

    max_count = max(count_dict.values())
    if max_count == 0:
        max_count = 1

    intensity_levels = [' ', '·', '•', '○', '●', '■', '█']

    map_rows = [list(row) for row in WORLD_MAP]

    for country, count in country_counts:
        if country not in COUNTRY_COORDS:
            continue
        y, x = COUNTRY_COORDS[country]
        if y >= len(map_rows) or x >= len(map_rows[y]):
            continue

        intensity = min(int((count / max_count) * (len(intensity_levels) - 1)),
                        len(intensity_levels) - 1)
        marker = intensity_levels[max(intensity, 2)]
        map_rows[y][x] = marker

    lines = []
    lines.append('')
    lines.append(f'  {title}')
    lines.append('  ' + '=' * len(title))
    lines.append('')

    map_str = '\n'.join('  ' + ''.join(row) for row in map_rows)
    lines.append(map_str)
    lines.append('')

    legend_title = '  Country Distribution:'
    lines.append(legend_title)
    lines.append('  ' + '-' * (len(legend_title) - 2))

    for country, count in country_counts[:15]:
        if country == 'Unknown':
            continue
        pct = count / total * 100
        bar_len = int(pct / 100 * 40)
        bar = '█' * bar_len + '░' * (40 - bar_len)
        name = country_name(country)
        display_name = name if len(name) <= 18 else name[:15] + '...'
        lines.append(
            f'  {country:2} {display_name:<20} {count:>8,} '
            f'({pct:5.1f}%) │{bar}│'
        )

    unknown_count = count_dict.get('Unknown', 0)
    if unknown_count > 0:
        pct = unknown_count / total * 100
        lines.append(
            f'  ?? Unknown              {unknown_count:>8,} '
            f'({pct:5.1f}%)'
        )

    lines.append('')
    lines.append('  Legend: · Low  • Medium  ○ High  ● Very High  ■ Extreme')
    lines.append('')

    return '\n'.join(lines)